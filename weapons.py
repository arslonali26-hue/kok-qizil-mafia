def resolve_weapon_id(weapon_id):
    return WEAPON_ALIASES.get(weapon_id, weapon_id)

def get_weapon(weapon_id):
    real_id = resolve_weapon_id(weapon_id)
    return WEAPONS.get(real_id)

MAX_WEAPON_LEVEL = 15
BASE_XP_CAPACITY = 100
LEVEL_2_XP_CAPACITY = 130
XP_GROWTH = 1.20
DAMAGE_GROWTH = 1.05


def xp_capacity(level, base_capacity=None):
    """Qurolning shu levelga o'tishi uchun kerak bo'ladigan XP.

    base_capacity:
        Qurolning magazindagi shop_xp qiymati.
        Berilmasa eski 100/130 tizimi saqlanadi.
    """
    level = max(1, min(int(level), MAX_WEAPON_LEVEL))

    if base_capacity is None:
        base_capacity = BASE_XP_CAPACITY

    base_capacity = max(1, int(base_capacity))

    # ⭐ Level 1 sig'imi aynan magazindagi shop_xp.
    if level == 1:
        return base_capacity

    # ⭐ Keyingi level sig'imi mavjud 1.20 o'sish formulasi bilan.
    capacity = base_capacity

    for _ in range(2, level + 1):
        capacity = max(1, int(round(capacity * XP_GROWTH)))

    return capacity


def weapon_damage(base_damage, level):
    """Qurolning levelga mos zarari."""
    base_damage = max(0, int(base_damage))
    level = max(1, min(int(level), MAX_WEAPON_LEVEL))

    damage = base_damage * (DAMAGE_GROWTH ** (level - 1))
    return max(base_damage, int(round(damage)))


def add_weapon_xp(xp, level, amount, base_capacity=None):
    """Qurol XP sini qo'shadi va yangi XP/levelni qaytaradi."""
    xp = max(0, int(xp))
    level = max(1, min(int(level), MAX_WEAPON_LEVEL))
    amount = max(0, int(amount))

    if level >= MAX_WEAPON_LEVEL:
        return xp, MAX_WEAPON_LEVEL

    xp += amount

    while level < MAX_WEAPON_LEVEL:
        required = xp_capacity(level, base_capacity)

        if xp < required:
            break

        xp -= required
        level += 1

    return xp, level

